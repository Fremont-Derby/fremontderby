import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const candidate = await readFile(new URL('scripts/sql/jfl-ordinary-score-ownership.candidate.sql',root),'utf8');
const baseline = JSON.parse(await readFile(new URL('test/fixtures/jfl-ordinary-score-baseline.json',root),'utf8'));
const md5 = body => createHash('md5').update(body.replaceAll('\r','')).digest('hex');
const functions = [...candidate.matchAll(/create or replace function\s+([\w.]+)\([\s\S]*?\bas\s+(\$\w+\$)([\s\S]*?)\2/gi)];
if(functions.length !== 9) throw new Error('Expected exactly eight candidate RPCs and one guard');
const pins = functions.map(([,name,,body]) => {
  const row = baseline.find(row => `jfl.${row.proname}` === name);
  const signature = row ? row.definition.match(/FUNCTION ([^(]+)\(([^\n]*)\)/)[0].replace(/^FUNCTION /,'').replace(/\((.*)\)/,(_,args)=>`(${args.split(',').map(arg=>arg.trim().split(/\s+/).at(-1)).join(',')})`) : 'jfl_private.require_current_scorekeeper(uuid,uuid,uuid)';
  return `('${signature}','${md5(body)}')`;
});
const sql = `-- SOURCE ONLY #3288 compensating recovery; never an automatic migration.
-- Generated by scripts/build-score-ownership-recovery.mjs. Qualify exact installed
-- candidate before restoring captured RPCs. Run as one transaction, never statements.
begin;
do $recovery$
begin
 if exists (
   select 1 from (values ${pins.join(',\n     ')}) expected(signature,body_md5)
   left join pg_proc p on p.oid=to_regprocedure(expected.signature)
   where p.oid is null or md5(replace(p.prosrc,chr(13),'')) <> expected.body_md5
     or p.proowner <> 'postgres'::regrole or not p.prosecdef
     or p.proconfig is distinct from array['search_path=""']::text[]
     or (select count(*) from aclexplode(coalesce(p.proacl,acldefault('f',p.proowner))) a
       where a.privilege_type='EXECUTE' and a.grantee in ('postgres'::regrole,'service_role'::regrole)) <> 2
     or exists (select 1 from aclexplode(coalesce(p.proacl,acldefault('f',p.proowner))) a
       where a.privilege_type <> 'EXECUTE' or a.is_grantable
         or a.grantee not in ('postgres'::regrole,'service_role'::regrole))
 ) then raise exception 'Unqualified committed ownership recovery baseline'; end if;
end;
$recovery$;
${baseline.map(row=>`${row.definition.trim()};`).join('\n\n')}
-- Restore all callers before removing only our exact guard. Never CASCADE.
drop function jfl_private.require_current_scorekeeper(uuid,uuid,uuid) restrict;
commit;
`;
await writeFile(new URL('scripts/sql/jfl-ordinary-score-ownership.recovery.sql',root),sql);
