#!/usr/bin/env node
/**
 * Stamp git SHA into src/routerEntry.js constants so the Worker bundle
 * always carries versionTag regardless of CF var binding / build cache quirks.
 */
import { readFileSync, writeFileSync, rmSync, existsSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const SHA_RE = /^[0-9a-f]{7,40}$/i;

/**
 * Preference order: GITHUB_SHA → WORKERS_CI_COMMIT_SHA → DEPLOY_GIT_SHA → git HEAD.
 * @param {NodeJS.ProcessEnv} [env]
 * @param {{ gitRevParse?: () => string | null }} [opts]
 */
export function resolveDeployIdentitySha(env = process.env, opts = {}) {
  const candidates = [
    env.GITHUB_SHA,
    env.WORKERS_CI_COMMIT_SHA,
    env.DEPLOY_GIT_SHA,
  ];
  for (const raw of candidates) {
    const value = String(raw || '').trim();
    if (value && SHA_RE.test(value)) return value;
  }
  if (typeof opts.gitRevParse === 'function') {
    const fromGit = String(opts.gitRevParse() || '').trim();
    if (fromGit && SHA_RE.test(fromGit)) return fromGit;
  }
  return null;
}

function gitHeadSha() {
  const git = spawnSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' });
  if (git.status === 0) return String(git.stdout || '').trim();
  return null;
}

export function stampDeployIdentity({ env = process.env, entryPath = 'src/routerEntry.js' } = {}) {
  const resolved = resolveDeployIdentitySha(env, { gitRevParse: gitHeadSha });
  if (!resolved) {
    console.warn('stamp-deploy-identity: no git sha available');
    return { stamped: false, sha: null };
  }

  const stampedAt = new Date().toISOString();
  let source = readFileSync(entryPath, 'utf8');
  if (!source.includes('const STAMPED_DEPLOY_GIT_SHA')) {
    throw new Error('stamp-deploy-identity: STAMPED_DEPLOY_GIT_SHA marker missing in routerEntry.js');
  }
  source = source.replace(
    /const STAMPED_DEPLOY_GIT_SHA = [^;]+;/,
    `const STAMPED_DEPLOY_GIT_SHA = ${JSON.stringify(resolved)};`,
  );
  source = source.replace(
    /const STAMPED_DEPLOY_AT = [^;]+;/,
    `const STAMPED_DEPLOY_AT = ${JSON.stringify(stampedAt)};`,
  );
  writeFileSync(entryPath, source);

  if (existsSync('.wrangler')) {
    rmSync('.wrangler', { recursive: true, force: true });
    console.log('cleared .wrangler cache');
  }

  writeFileSync(
    'src/deployIdentity.js',
    `/** Generated by scripts/stamp-deploy-identity.mjs — do not edit. */
export const DEPLOY_IDENTITY = {
  gitSha: ${JSON.stringify(resolved)},
  stampedAt: ${JSON.stringify(stampedAt)},
};
`,
  );

  const verify = readFileSync(entryPath, 'utf8');
  if (!verify.includes(JSON.stringify(resolved))) {
    throw new Error('stamp-deploy-identity: verification failed');
  }
  console.log('stamped deploy identity', resolved, stampedAt);
  return { stamped: true, sha: resolved, stampedAt };
}

const isDirect = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isDirect) {
  try {
    stampDeployIdentity();
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
}
