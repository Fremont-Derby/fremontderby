#!/usr/bin/env node
/**
 * Stamp src/deployIdentity.js with the git SHA so /health versionTag
 * does not depend on Cloudflare var binding quirks.
 */
import { writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';

const sha = String(
  process.env.GITHUB_SHA ||
    process.env.WORKERS_CI_COMMIT_SHA ||
    process.env.DEPLOY_GIT_SHA ||
    '',
).trim();

let resolved = sha;
if (!resolved || !/^[0-9a-f]{7,40}$/i.test(resolved)) {
  const git = spawnSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' });
  if (git.status === 0) resolved = String(git.stdout || '').trim();
}

if (!resolved || !/^[0-9a-f]{7,40}$/i.test(resolved)) {
  console.warn('stamp-deploy-identity: no git sha available; leaving null');
  process.exit(0);
}

const stampedAt = new Date().toISOString();
const body = `/** Generated by scripts/stamp-deploy-identity.mjs — do not edit. */
export const DEPLOY_IDENTITY = {
  gitSha: ${JSON.stringify(resolved)},
  stampedAt: ${JSON.stringify(stampedAt)},
};
`;
writeFileSync('src/deployIdentity.js', body);
console.log('stamped deploy identity', resolved, stampedAt);
