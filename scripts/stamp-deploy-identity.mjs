#!/usr/bin/env node
/**
 * Stamp git SHA into src/routerEntry.js constants so the Worker bundle
 * always carries versionTag regardless of CF var binding / build cache quirks.
 */
import { readFileSync, writeFileSync, rmSync, existsSync } from 'node:fs';
import { resolveStampSha } from './resolveStampSha.mjs';

const resolved = resolveStampSha(process.env);

if (!resolved) {
  console.warn('stamp-deploy-identity: no git sha available');
  process.exit(0);
}

const stampedAt = new Date().toISOString();
const entryPath = 'src/routerEntry.js';
let source = readFileSync(entryPath, 'utf8');
if (!source.includes('const STAMPED_DEPLOY_GIT_SHA')) {
  console.error('stamp-deploy-identity: STAMPED_DEPLOY_GIT_SHA marker missing in routerEntry.js');
  process.exit(1);
}
source = source.replace(
  /const STAMPED_DEPLOY_GIT_SHA = [^;]+;/,
  `const STAMPED_DEPLOY_GIT_SHA = ${JSON.stringify(resolved)};`,
);
source = source.replace(
  /const STAMPED_DEPLOY_AT = [^;]+;/,
  `const STAMPED_DEPLOY_AT = ${JSON.stringify(stampedAt)};`,
);
writeFileSync(entryPath, source);

if (existsSync('.wrangler')) {
  rmSync('.wrangler', { recursive: true, force: true });
  console.log('cleared .wrangler cache');
}

writeFileSync(
  'src/deployIdentity.js',
  `/** Generated by scripts/stamp-deploy-identity.mjs — do not edit. */
export const DEPLOY_IDENTITY = {
  gitSha: ${JSON.stringify(resolved)},
  stampedAt: ${JSON.stringify(stampedAt)},
};
`,
);

// Verify stamp landed
const verify = readFileSync(entryPath, 'utf8');
if (!verify.includes(JSON.stringify(resolved))) {
  console.error('stamp-deploy-identity: verification failed');
  process.exit(1);
}
console.log('stamped deploy identity', resolved, stampedAt);
