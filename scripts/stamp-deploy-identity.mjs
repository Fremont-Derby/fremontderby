#!/usr/bin/env node
/**
 * Stamp git SHA into src/routerEntry.js constants so the Worker bundle
 * always carries versionTag regardless of CF var binding / build cache quirks.
 */
import { readFileSync, writeFileSync, rmSync, existsSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

export const GIT_SHA_RE = /^[0-9a-f]{7,40}$/i;

export function isValidGitSha(value) {
  return GIT_SHA_RE.test(String(value || '').trim());
}

/** Resolve SHA from env first, then optional git fallback. Pure when spawn is injected. */
export function resolveDeployGitSha(
  env = process.env,
  { spawnSync: spawn = spawnSync } = {},
) {
  const fromEnv = String(
    env.GITHUB_SHA || env.WORKERS_CI_COMMIT_SHA || env.DEPLOY_GIT_SHA || '',
  ).trim();
  if (isValidGitSha(fromEnv)) return fromEnv;

  const git = spawn('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' });
  if (git.status === 0) {
    const fromGit = String(git.stdout || '').trim();
    if (isValidGitSha(fromGit)) return fromGit;
  }
  return null;
}

/** Pure string transform of routerEntry source. */
export function applyStampToRouterSource(source, sha, stampedAt) {
  if (!String(source || '').includes('const STAMPED_DEPLOY_GIT_SHA')) {
    return {
      ok: false,
      error: 'stamp-deploy-identity: STAMPED_DEPLOY_GIT_SHA marker missing in routerEntry.js',
    };
  }
  let next = source.replace(
    /const STAMPED_DEPLOY_GIT_SHA = [^;]+;/,
    `const STAMPED_DEPLOY_GIT_SHA = ${JSON.stringify(sha)};`,
  );
  next = next.replace(
    /const STAMPED_DEPLOY_AT = [^;]+;/,
    `const STAMPED_DEPLOY_AT = ${JSON.stringify(stampedAt)};`,
  );
  if (!next.includes(JSON.stringify(sha))) {
    return { ok: false, error: 'stamp-deploy-identity: verification failed' };
  }
  return { ok: true, source: next };
}

export function buildDeployIdentityModule(sha, stampedAt) {
  return `/** Generated by scripts/stamp-deploy-identity.mjs — do not edit. */
export const DEPLOY_IDENTITY = {
  gitSha: ${JSON.stringify(sha)},
  stampedAt: ${JSON.stringify(stampedAt)},
};
`;
}

export function runStampDeployIdentity({
  env = process.env,
  entryPath = 'src/routerEntry.js',
  identityPath = 'src/deployIdentity.js',
  readFileSync: readFile = readFileSync,
  writeFileSync: writeFile = writeFileSync,
  existsSync: exists = existsSync,
  rmSync: rm = rmSync,
  spawnSync: spawn = spawnSync,
  now = () => new Date().toISOString(),
} = {}) {
  const resolved = resolveDeployGitSha(env, { spawnSync: spawn });
  if (!resolved) {
    return { ok: true, skipped: true, reason: 'no git sha available' };
  }

  const stampedAt = now();
  const source = readFile(entryPath, 'utf8');
  const stamped = applyStampToRouterSource(source, resolved, stampedAt);
  if (!stamped.ok) return stamped;

  writeFile(entryPath, stamped.source);
  if (exists('.wrangler')) {
    rm('.wrangler', { recursive: true, force: true });
  }
  writeFile(identityPath, buildDeployIdentityModule(resolved, stampedAt));
  return { ok: true, skipped: false, sha: resolved, stampedAt };
}

const isDirect =
  process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1]);
if (isDirect) {
  const result = runStampDeployIdentity();
  if (!result.ok) {
    console.error(result.error);
    process.exit(1);
  }
  if (result.skipped) {
    console.warn('stamp-deploy-identity: no git sha available');
    process.exit(0);
  }
  if (existsSync('.wrangler') === false) {
    /* already cleared inside runner when present */
  }
  console.log('stamped deploy identity', result.sha, result.stampedAt);
}
