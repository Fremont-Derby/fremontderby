#!/usr/bin/env node
/**
 * Stamp git SHA into src/routerEntry.js constants so the Worker bundle
 * always carries versionTag regardless of CF var binding / build cache quirks.
 */
import { readFileSync, writeFileSync, rmSync, existsSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

export const GIT_SHA_RE = /^[0-9a-f]{7,40}$/i;
export const ROUTER_ENTRY_PATH = 'src/routerEntry.js';
export const DEPLOY_IDENTITY_PATH = 'src/deployIdentity.js';

/**
 * Resolve deploy git SHA from env, then optional git rev-parse.
 * Pure aside from the injectable spawn.
 */
export function resolveDeployGitSha(env = process.env, spawn = spawnSync) {
  const candidates = [
    env.GITHUB_SHA,
    env.WORKERS_CI_COMMIT_SHA,
    env.DEPLOY_GIT_SHA,
  ];
  for (const raw of candidates) {
    const value = String(raw || '').trim();
    if (value && GIT_SHA_RE.test(value)) return value;
  }

  const git = spawn('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' });
  if (git.status === 0) {
    const value = String(git.stdout || '').trim();
    if (value && GIT_SHA_RE.test(value)) return value;
  }
  return null;
}

/**
 * Apply stamp constants into routerEntry source. Pure string transform.
 * Throws if the STAMPED_DEPLOY_GIT_SHA marker is missing.
 */
export function applyStampToRouterSource(source, sha, stampedAt) {
  if (!String(source || '').includes('const STAMPED_DEPLOY_GIT_SHA')) {
    throw new Error('stamp-deploy-identity: STAMPED_DEPLOY_GIT_SHA marker missing in routerEntry.js');
  }
  let next = source.replace(
    /const STAMPED_DEPLOY_GIT_SHA = [^;]+;/,
    `const STAMPED_DEPLOY_GIT_SHA = ${JSON.stringify(sha)};`,
  );
  next = next.replace(
    /const STAMPED_DEPLOY_AT = [^;]+;/,
    `const STAMPED_DEPLOY_AT = ${JSON.stringify(stampedAt)};`,
  );
  return next;
}

/** Generated module source for src/deployIdentity.js. */
export function deployIdentityModuleSource(sha, stampedAt) {
  return `/** Generated by scripts/stamp-deploy-identity.mjs — do not edit. */
export const DEPLOY_IDENTITY = {
  gitSha: ${JSON.stringify(sha)},
  stampedAt: ${JSON.stringify(stampedAt)},
};
`;
}

export function runStampDeployIdentity({
  env = process.env,
  spawn = spawnSync,
  readFile = readFileSync,
  writeFile = writeFileSync,
  remove = rmSync,
  exists = existsSync,
  now = () => new Date().toISOString(),
} = {}) {
  const resolved = resolveDeployGitSha(env, spawn);
  if (!resolved) {
    console.warn('stamp-deploy-identity: no git sha available');
    return { ok: true, stamped: false };
  }

  const stampedAt = now();
  const source = readFile(ROUTER_ENTRY_PATH, 'utf8');
  const next = applyStampToRouterSource(source, resolved, stampedAt);
  writeFile(ROUTER_ENTRY_PATH, next);

  if (exists('.wrangler')) {
    remove('.wrangler', { recursive: true, force: true });
    console.log('cleared .wrangler cache');
  }

  writeFile(DEPLOY_IDENTITY_PATH, deployIdentityModuleSource(resolved, stampedAt));

  const verify = readFile(ROUTER_ENTRY_PATH, 'utf8');
  if (!verify.includes(JSON.stringify(resolved))) {
    throw new Error('stamp-deploy-identity: verification failed');
  }
  console.log('stamped deploy identity', resolved, stampedAt);
  return { ok: true, stamped: true, sha: resolved, stampedAt };
}

const isDirect =
  process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isDirect) {
  try {
    runStampDeployIdentity();
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
}
