import test from 'node:test';
import assert from 'node:assert/strict';
import { canaryCheck, closeKeyword, finalScore, laneBase, matchComplete, mockSeason, playerResult, shippingBlocker } from '../src/resultGate.js';
test('a mock season is simple', () => { assert.equal(mockSeason({ name: 'Week', simple: false }).ok, false); });
test('a finished match shows the score', () => { assert.equal(finalScore({ final: true, score: '3-1' }).shown, true); });
test('a player result names the points', () => { assert.equal(playerResult({ player: 'Eli' }).ok, false); });
test('a lane names its base', () => { assert.equal(laneBase({ lane: 'dru', base: 'fremontderby-dru' }).ok, true); });
test('a canary names the failed check', () => { assert.equal(canaryCheck({ name: 'home', status: 200 }).ok, true); });
test('a won match does not add a rack', () => { assert.match(matchComplete({ won: true, racks: 3 }).text, /No extra rack/); });
test('a blocker names the lane and the why', () => { assert.equal(shippingBlocker({ lane: 'dru' }).named, false); });
test('close keywords are limited', () => { assert.equal(closeKeyword('fixes').ok, false); });
